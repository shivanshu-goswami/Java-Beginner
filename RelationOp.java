public class RelationOp {
    public static void main(String a[]){
        int x=6;
        int y=5;

        boolean res= x>y; //true
        System.out.println(res);

        res= x<y;
        System.out.println(res);

        res= x>=y;
        System.out.println(res);

        res= x<=y;
        System.out.println(res);

        res= x==y;
        System.out.println(res);

        res= x!=y;
        System.out.println(res);

        double c=8.8;
        double b= 9.8;

        res= c<b;
        System.out.println(res);


    }
}
